import os
import json
import subprocess
import gradio as gr
from pathlib import Path

# Initialize Gemini client if API key available
def get_gemini_client():
    api_key = os.getenv("GEMINI_API_KEY") or os.getenv("GOOGLE_API_KEY")
    if not api_key:
        for env_path in [".env", "cloudflare.env", "fair_dinkum_publishing/.env"]:
            if os.path.exists(env_path):
                with open(env_path, "r") as f:
                    for line in f:
                        if "GEMINI_API_KEY" in line or "GOOGLE_API_KEY" in line:
                            parts = line.strip().split("=", 1)
                            if len(parts) == 2:
                                api_key = parts[1].strip().strip("'\"")
                                break
    if api_key:
        try:
            from google import genai
            return genai.Client(api_key=api_key)
        except Exception as e:
            print(f"[Warning] Failed to init google-genai client: {e}")
    return None

def generate_content(prompt, content_type, tone):
    client = get_gemini_client()
    system_instruction = f"You are an expert autonomous content creator for Fair Dinkum Press. Generate high-converting {content_type} with a {tone} tone. Return clean Markdown format."
    
    full_prompt = f"{system_instruction}\n\nTask/Topic: {prompt}"
    
    if client:
        try:
            response = client.models.generate_content(
                model="gemini-3.5-flash-lite",
                contents=full_prompt
            )
            return response.text
        except Exception as e:
            print(f"[Error calling Gemini API: {e}]")
            
    # Fallback simulation if API key missing
    return f"""# Generated {content_type.title()} ({tone.title()} Tone)

## Executive Summary
This is an AI-generated draft based on your prompt: **"{prompt}"**

### Key Points
1. Strategic Alignment with Fair Dinkum Publishing & Solopreneur Workforces.
2. Optimized for conversion, clarity, and autonomous execution.
3. Fully compliant with Australian B2B standards.

*Generated by Gemini 3.5 Flash-Lite via Fair Dinkum Studio.*
"""

def get_filetree():
    """Builds filetree representation of workspace key directories."""
    root = Path(".")
    tree_str = "📂 Workspace FileTree\n"
    target_dirs = ["docs", "scripts", "outputs", "web", "qwen-social-studio", "contents-generator-app"]
    
    for d in target_dirs:
        p = root / d
        if p.exists() and p.is_dir():
            tree_str += f"└── 📁 {d}/\n"
            for item in sorted(p.glob("*"))[:8]:
                tree_str += f"    ├── {item.name}\n"
    return tree_str

def save_content(filename, content):
    if not filename:
        filename = "generated_content.md"
    os.path.abspath("outputs")
    os.makedirs("outputs", exist_ok=True)
    filepath = os.path.join("outputs", filename)
    with open(filepath, "w") as f:
        f.write(content)
    return f"Successfully saved to {filepath}"

def send_content(recipient, subject, content):
    """Sends generated content via Composio Gmail."""
    try:
        payload = json.dumps({"recipient_email": recipient, "subject": subject, "body_text": content})
        res = subprocess.run(["composio", "execute", "GMAIL_SEND_EMAIL", "-d", payload], capture_output=True, text=True, timeout=15)
        return f"Successfully sent email to {recipient}: {res.stdout.strip()}"
    except Exception as e:
        return f"Failed to send email: {e}"

# Gradio Interface
with gr.Blocks(theme=gr.themes.Soft(primary_hue="emerald", secondary_hue="blue")) as demo:
    gr.Markdown("# 📝 Fair Dinkum Contents Generator & AI Studio")
    gr.Markdown("Powered by **Gemini 3.5 Flash-Lite** • FileTree Organiser • Live Preview • One-Click Save & Send.")
    
    with gr.Row():
        with gr.Column(scale=1):
            gr.Markdown("### 📂 Workspace Organiser")
            filetree_box = gr.Textbox(value=get_filetree(), label="FileTree Organiser", lines=12, interactive=False)
            refresh_btn = gr.Button("🔄 Refresh FileTree")
            
            gr.Markdown("### ⚙️ Generation Parameters")
            content_type = gr.Dropdown(choices=["Blog Post", "LinkedIn Article", "Email Newsletter", "Product Launch Copy", "Compliance Report"], value="LinkedIn Article", label="Content Type")
            tone = gr.Dropdown(choices=["Professional", "Authoritative", "Persuasive", "Casual & Direct", "Enthusiastic"], value="Professional", label="Tone")
            
        with gr.Column(scale=2):
            gr.Markdown("### 🤖 Gemini 3.5 Flash-Lite Prompt Box")
            prompt_box = gr.Textbox(label="Prompt / Topic Instruction", value="Announcing the launch of our autonomous AI compliance auditing tool for Australian fintech lenders.", lines=3)
            gen_btn = gr.Button("✨ Generate Content", variant="primary")
            
            gr.Markdown("### 👁️ Live Preview Window")
            preview_box = gr.Markdown(value="*Generated content preview will appear here...*", label="Live Preview")
            raw_editor = gr.Textbox(label="Raw Markdown Editor", lines=8)
            
            with gr.Row():
                filename_input = gr.Textbox(label="Filename", value="generated_article.md", scale=1)
                save_btn = gr.Button("💾 Save Locally", variant="secondary", scale=1)
                
            with gr.Row():
                recipient_input = gr.Textbox(label="Recipient Email", value="brettanthonysjoberg179@gmail.com", scale=1)
                subject_input = gr.Textbox(label="Email Subject", value="Fair Dinkum Content Draft", scale=1)
                send_btn = gr.Button("✉️ Send via Gmail", variant="secondary", scale=1)
                
            status_output = gr.Textbox(label="Action Status", lines=2, interactive=False)

    refresh_btn.click(fn=get_filetree, outputs=filetree_box)
    
    gen_btn.click(
        fn=generate_content,
        inputs=[prompt_box, content_type, tone],
        outputs=[raw_editor]
    )
    
    # Mirror raw editor to preview
    raw_editor.change(fn=lambda x: x, inputs=raw_editor, outputs=preview_box)
    
    save_btn.click(
        fn=save_content,
        inputs=[filename_input, raw_editor],
        outputs=[status_output]
    )
    
    send_btn.click(
        fn=send_content,
        inputs=[recipient_input, subject_input, raw_editor],
        outputs=[status_output]
    )

if __name__ == "__main__":
    demo.launch(server_name="0.0.0.0", server_port=7861, share=True)
